    public static func messages(for locale: AppLocale) -> [String: String] {
        switch locale {
        case .english: englishMessages
        case .simplifiedChinese: simplifiedChineseMessages
        }
    }

    /// Mirrors core.ts: selected-locale lookup first, then English. Swift views
    /// accept string keys, so an impossible-at-compile-time TypeScript key is
    /// returned unchanged rather than producing an empty UI label.
    public static func text(
        _ key: String,
        locale: AppLocale,
        parameters: [String: String] = [:]
    ) -> String {
        var message = messages(for: locale)[key] ?? englishMessages[key] ?? key
        for (name, value) in parameters {
            message = message.replacingOccurrences(of: "{{\(name)}}", with: value)
        }
        return message
    }

    public static func translator(for locale: AppLocale) -> ArcoTranslate {
        { key, parameters in
            text(key, locale: locale, parameters: parameters)
        }
    }

    public static var english: ArcoTranslate {
        translator(for: .english)
    }

    public static var simplifiedChinese: ArcoTranslate {
        translator(for: .simplifiedChinese)
    }
}

/// Native equivalent of I18nProvider: it resolves the persisted locale once,
/// persists explicit changes under the same key, and exposes an ArcoTranslate
/// closure for the SwiftUI view tree.
@MainActor
@Observable
public final class ArcoLocalization {
    public static let localeStorageKey = "arco.locale"

    public private(set) var locale: AppLocale

    private let preferences: ArcoPreferences

    public init(
        preferences: ArcoPreferences = ArcoPreferences(),
        preferredLanguages: [String] = Locale.preferredLanguages
    ) {
        self.preferences = preferences
        locale = preferences.loadLocale(preferredLanguages: preferredLanguages)
    }

    public var translate: ArcoTranslate {
        ArcoTranslations.translator(for: locale)
    }

    public func text(_ key: String, parameters: [String: String] = [:]) -> String {
        ArcoTranslations.text(key, locale: locale, parameters: parameters)
    }

    public func setLocale(_ nextLocale: AppLocale) {
        preferences.saveLocale(nextLocale)
        locale = nextLocale
    }

    /// Mirrors the browser storage-event path: external values update current
    /// state after normalization but are not written back a second time.
    public func synchronize(
        storedLocale: String?,
        preferredLanguages: [String] = Locale.preferredLanguages
    ) {
        locale = Self.resolveLocale(
            storedLocale: storedLocale,
            preferredLanguages: preferredLanguages
        )
    }

    /// Exact resolveLocale semantics from core.ts: saved values are accepted
    /// only when they exactly match a supported locale; otherwise any zh-prefixed
    /// preferred language selects Simplified Chinese and all others select English.
    public static func resolveLocale(
        storedLocale: String?,
        preferredLanguages: [String] = []
    ) -> AppLocale {
        if let storedLocale, let locale = AppLocale(rawValue: storedLocale) {
            return locale
        }
        return preferredLanguages.contains { $0.lowercased().hasPrefix("zh") }
            ? .simplifiedChinese
            : .english
    }
}

/// Direct Swift ports of the two formatting helpers exported by core.ts.
public func formatDurationLabel(_ durationLabel: String, translate: ArcoTranslate) -> String {
    let trimmed = durationLabel.trimmingCharacters(in: .whitespacesAndNewlines)
    let range = NSRange(trimmed.startIndex..<trimmed.endIndex, in: trimmed)
    guard
        let expression = try? NSRegularExpression(
            pattern: "^([0-9]+)\\s*(?:m|min)$",
            options: [.caseInsensitive]
        ),
        let match = expression.firstMatch(in: trimmed, range: range),
        let countRange = Range(match.range(at: 1), in: trimmed),
        let count = Int(trimmed[countRange])
    else {
        return durationLabel
    }
    return translate("history.durationMinutes", ["count": String(count)])
}

public func localizedSpeakerLabel(_ speaker: String, translate: ArcoTranslate) -> String {
    let range = NSRange(speaker.startIndex..<speaker.endIndex, in: speaker)
    let number = (try? NSRegularExpression(pattern: "[0-9]+"))
        .flatMap { $0.firstMatch(in: speaker, range: range) }
        .flatMap { Range($0.range, in: speaker) }
        .map { String(speaker[$0]) } ?? "1"
    let normalized = speaker.lowercased()
    if normalized.hasPrefix("remote") {
        return translate("transcript.remoteSpeaker", ["number": number])
    }
    if normalized.hasPrefix("in room") {
        return translate("transcript.roomSpeaker", ["number": number])
    }
    return speaker
}
